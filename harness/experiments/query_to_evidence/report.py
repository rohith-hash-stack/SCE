"""Render results.json as a Markdown report (tables only; no interpretation
beyond what the numbers say - findings are written by hand in README)."""
from __future__ import annotations

from collections import Counter

KEYS = [("subject_resolution", "subject"), ("manifest_recall", "manifest"), ("requested_recall", "requested"), ("selected_recall", "requested or auto-included"),
        ("delivered_recall", "delivered"), ("delivered_full", "full"), ("delivered_stub_only", "stub only"),
        ("edges_in_graph", "edges in graph"), ("edge_constructed_in_package", "edge in package"),
        ("edge_call_site_in_model_input", "call site in input"), ("relationship_record_delivered", "edge record in input"),
        ("source_evidence_in_model_input", "source evidence in input")]


def _fmt(v) -> str:
    if isinstance(v, dict) and "num" in v:
        return f"{v['num']}/{v['den']}" if v["den"] else "n/a (0 den)"
    return str(v) if v is not None else "-"


def _counter(d) -> str:
    return ", ".join(f"{k}: {v}" for k, v in sorted(d.items(), key=lambda kv: -kv[1])) if d else "-"


def render(result: dict) -> str:
    m = result["metrics"]
    out = ["# Query-to-evidence evaluation", "",
           "Diagnostic only. Generated by `python -m harness.experiments.query_to_evidence.run`; "
           "see `harness/experiments/query_to_evidence/README.md` for definitions. Ratios are `num/den`; "
           "`n/a` = no denominator; `not measured` = the stage was not run.", "",
           f"Tokenizer: {result['environment']['tokenizer']}; harness trim counted with "
           f"{result['environment']['harness_tokenizer_stand_in']}.", ""]
    if result.get("dataset_problems"):
        out += ["**Dataset problems:**", *[f"- {p}" for p in result["dataset_problems"]], ""]
    for mode, title in (("production", "Production inputs"), ("counterfactual", "Counterfactual: gold subject supplied as seed (not a production path)"),
                        ("stored_cell", "Stored s42 cells (controls only)")):
        out += [f"## Per category - {title}", "", "| category | " + " | ".join(h for _k, h in KEYS) + " | first loss |",
                "|---|" + "---|" * (len(KEYS) + 1)]
        for cat in ("seeded_control", "unseeded_behavioral", "compound", "ambiguous", "unanswerable"):
            row = m["per_category"].get(cat, {}).get(mode, "n/a")
            if not isinstance(row, dict):
                out.append(f"| {cat} | " + " | ".join("n/a" for _ in KEYS) + " | - |")
                continue
            out.append(f"| {cat} | " + " | ".join(_fmt(row.get(k)) for k, _h in KEYS) + f" | {_counter(row.get('first_loss', {}))} |")
        out.append("")
    out += ["## Per question", "", "| id | category | mode | delivered | full | stub | call sites | first loss | secondary causes |",
            "|---|---|---|---|---|---|---|---|---|"]
    for qid, q in m["per_question"].items():
        for mode in ("production", "counterfactual"):
            r = q[mode]
            if "status" in r:
                out.append(f"| {qid} | {q['category']} | {mode} | {r['status']} | | | | | |")
                continue
            out.append(f"| {qid} | {q['category']} | {mode} | {_fmt(r['delivered_recall'])} | {_fmt(r['delivered_full'])} | "
                       f"{_fmt(r['delivered_stub_only'])} | {_fmt(r['edge_call_site_in_model_input'])} | "
                       f"{_counter(r['first_loss'])} | {_counter(r['secondary_causes'])} |")
    out.append("")
    out += ["## Edge graph status (all modes' gold edges, counterfactual run)", ""]
    statuses = Counter()
    for q in m["per_question"].values():
        if "edge_graph_status" in q["counterfactual"]:
            statuses.update(q["counterfactual"]["edge_graph_status"])
    out += [f"- {k}: {v}" for k, v in sorted(statuses.items())] + [""]
    out += ["## Baseline comparison (seeded controls vs stored s42 cells)", "",
            "| id | run@commit | requested | delivered symbols | stubs | item text | prompt | stored drop | replay drop | stored pre-trim (Qwen) | replay pre-trim (cl100k) |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for q in result["questions"]:
        b = q["production"].get("baseline")
        if not b:
            continue
        yn = lambda x: "same" if x else "DIFF"
        out.append(f"| {q['id']} | {b['run']}@{b['commit']} | {yn(b['same_requested'])} | {yn(b['same_delivered_symbols'])} | "
                   f"{yn(b['same_stub_symbols'])} | {yn(b['same_item_content'])} | {yn(b['same_prompt'])} | {b['stored_budget_dropped']} | "
                   f"{b['replay_budget_dropped']} | {b['stored_pre_trim_tokens_qwen']} | {b['replay_pre_trim_tokens_cl100k']} |")
    out.append("")
    a = m["answer_controls"]
    out += ["## Answers (stored completions of the controls; graded against the stored input)", ""]
    if isinstance(a, dict):
        out += [f"- {k}: {_fmt(v)}" for k, v in a.items()] + [""]
        out += ["| id | named | gold named / gold | full | stub | not delivered | supported claims | correct but unsupported |",
                "|---|---|---|---|---|---|---|---|"]
        for q in result["questions"]:
            ans = q["production"].get("answer", {})
            if ans.get("status") != "graded":
                continue
            s = ans["summary"]
            out.append(f"| {q['id']} | {s['named']} | {s['gold_named']}/{s['gold_total']} | {s['named_full']} | {s['named_stub']} | "
                       f"{s['named_absent']} | {s['path_supported']}/{s['path_claims']} | {s['correct_but_unsupported']} |")
        out.append("")
    else:
        out += [str(a), ""]
    mg = result.get("manual_grounding")
    if mg:
        out += ["## Prose claims - manual subset", "", f"_{mg['label']}_", "",
                "Verdicts: " + ", ".join(f"{k}: {v}" for k, v in sorted(mg["verdicts"].items())) + f" (of {len(mg['claims'])}).", "",
                "| id | claim | verdict |", "|---|---|---|"]
        out += [f"| {c['id']} | {c['claim']} | {c['verdict']} |" for c in mg["claims"]] + [""]
    out += ["## Ambiguous and unanswerable", ""]
    for q in result["questions"]:
        if "ambiguity" in q:
            interp = "; ".join(f"{i['label']} ({i['indexed']}/{len(i['symbols'])} indexed)" for i in q["ambiguity"]["interpretations"])
            out.append(f"- {q['id']} (ambiguous): {q['ambiguity']['outcome']}. Interpretations: {interp}.")
        if "unanswerable" in q:
            u = q["unanswerable"]
            out.append(f"- {q['id']} (unanswerable): {u['classification']}; retrieval: {u['retrieval_outcome']}; abstention: {u['abstention']}.")
    out.append("")
    c = m["cost_controls"]
    out += ["## Cost (seeded controls, offline replay)", "",
            f"- retrieval latency median: {c['retrieve_ms_median']} ms (offline, includes no model time)",
            f"- prompt tokens median (cl100k): {c['prompt_tokens_cl100k_median']}",
            f"- context budget use median: {c['budget_use_median']}", ""]
    dm = result.get("delivery_modes")
    if dm:
        out += ["## Gold-edge delivery by mode", "",
                "Arm 5 rows are the benchmark prompt (header + body items only; no `<edges>`/`<contract>`/`<warnings>`). "
                "The other rows parse the real `prism.slice` / `prism.blast_radius` envelopes, seeded with the gold subject. "
                "Denominator = gold edges in scope for the mode.", "",
                "| mode | kind | edges | in graph | both ends selected | `<edge>` record | contract on callee | call site in full body | first loss | envelopes with BUDGET_OVERFLOW |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for name, m in dm.items():
            s_ = m["summary"]
            fl = _counter(s_.get("first_loss", {})) if "first_loss" in s_ else "-"
            bo = s_.get("envelopes_with_warning", {}).get("BUDGET_OVERFLOW", 0) if "envelopes" in s_ else "-"
            bo = f"{bo}/{s_['envelopes']}" if "envelopes" in s_ else bo
            out.append(f"| {name} | {m['kind']} | {s_['edges']} | {_fmt(s_.get('in_graph'))} | {_fmt(s_.get('both_selected'))} | "
                       f"{_fmt(s_.get('edge_record'))} | {_fmt(s_.get('contract')) if 'contract' in s_ else '-'} | "
                       f"{_fmt(s_.get('call_site_in_full_caller_body'))} | {fl} | {bo} |")
        out.append("")
    eq = result.get("equivalence") or []
    out += ["## Instrumentation equivalence (tracer on vs off)", ""]
    if eq:
        ok = sum(1 for r in eq if r["identical"])
        out.append(f"{ok}/{len(eq)} runs identical (requested symbols, raw items, delivered items with content and tokens, "
                   "budget drops, model input).")
        out += [f"- DIFF {r['id']} {r['run']}: {r}" for r in eq if not r["identical"]]
    else:
        out.append("not run")
    out.append("")
    return "\n".join(out)
